-- Run against nl2sql_db with the application database user. Safe to repeat.
CREATE SCHEMA IF NOT EXISTS nl2sql_internal;
CREATE TABLE IF NOT EXISTS nl2sql_internal.query_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question text NOT NULL,
    generated_sql text,
    validated_sql text,
    attempted_sql text,
    generation_status text NOT NULL DEFAULT 'pending',
    generation_error text,
    validation_status text NOT NULL DEFAULT 'not_started',
    validation_error text,
    execution_status text NOT NULL DEFAULT 'not_started',
    execution_error text,
    execution_duration_ms double precision,
    row_count integer,
    truncated boolean,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS query_history_created_idx ON nl2sql_internal.query_history (created_at DESC, id DESC);
